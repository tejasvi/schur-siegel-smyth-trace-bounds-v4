#!/usr/bin/env python3
"""Generate the K energy assembly of the 86a lower bound (fork of the companion areal formalization's
tools/gen_arl_ekassembly.py):
  Trace86/EKRnnn.lean : row sums rowK i from the chunk shards (T86K/EchkNNNN.lean) and segment sums of blkK;
  Trace86/EnergyK.lean: (iBlock 0 NREC).1 = total, the energy inequality (K) and IR_ge_K.
Inputs: T86K/ELits.lean, scratch/echunk_vals.txt, scratch/echunk_map.txt, scratch/eblock_total.txt. Paths are relative
to the project root (the parent of tools/).
usage: python3 -I gen86_ekassembly.py"""
import os, re
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(f'{H}/T86K/ELits.lean').read()
i0 = s.index('def recsILit'); j0 = s.index(']', s.index('[', i0))
sg = [int(r.strip('()')) for r in re.findall(r'⟨\d+, (\(?-?\d+\)?), \(?-?\d+\)?, \(?-?\d+\)?⟩', s[i0:j0 + 1])]
NREC = len(sg)
chunks = {}
for l in open(f'{H}/scratch/echunk_vals.txt'):
    i, a, m, lo = (int(x) for x in l.split())
    chunks.setdefault(i, []).append((a, m, lo))
fmap = {}
for l in open(f'{H}/scratch/echunk_map.txt'):
    i, a, m, f = (int(x) for x in l.split())
    fmap[(i, a)] = f
def lit(v): return f'({v})' if v < 0 else str(v)
rowval = [0] * NREC
for i in range(NREC):
    if sg[i] != 0:
        rowval[i] = sum(c[2] for c in chunks.get(i, []))
TOTAL = sum(rowval)
tot = open(f'{H}/scratch/eblock_total.txt').read()
assert TOTAL == int(re.search(r'lo (-?\d+)', tot).group(1))
ROWS_PER = 100
segs = []
for k, rs in enumerate(range(0, NREC, ROWS_PER)):
    re_ = min(NREC, rs + ROWS_PER)
    files = sorted({fmap[(i, c[0])] for i in range(rs, re_) if sg[i] != 0 for c in chunks.get(i, [])})
    out = [f'import T86K.Echk{f:04d}' for f in files] + ['import Trace86.EnergyKLemmas', '',
           f'/-! Energy rows {rs} .. {re_ - 1} (K): row sums from the chunks, and the segment sum. Generated by',
           'tools/gen86_ekassembly.py. -/', '', 'set_option maxRecDepth 200000', 'set_option maxHeartbeats 0', '',
           'namespace Trace86.Cert', '', 'open T86Core AuxCore AuxCommon', '']
    for i in range(rs, re_):
        if sg[i] == 0:
            continue
        cs = chunks.get(i, [])
        if not cs:
            out.append(f'theorem rk_{i} : rowK {i} = 0 :=')
            out.append(f'  rowK_eq {i} (by rw [List.drop_eq_nil_of_le (by rw [recsILit_length])]; rfl)')
            continue
        ps = [0] * len(cs)
        acc = 0
        for t in range(len(cs) - 1, -1, -1):
            acc += cs[t][2]; ps[t] = acc
        a, m, lo = cs[-1]
        expr = f'rowK_of_chunks_last {i} {a} {m} (by norm_num) T86Core.T86K.ec_{i}_{a}'
        for t in range(len(cs) - 2, -1, -1):
            a, m, lo = cs[t]
            b = cs[t + 1][0]
            expr = (f'rowK_of_chunks_step (s := {lit(ps[t])}) {i} {a} {m} {b} (by norm_num) T86Core.T86K.ec_{i}_{a}\n    ({expr})\n'
                    f'    (by norm_num)')
        out.append(f'theorem rk_{i} : rowK {i} = {lit(ps[0])} :=')
        out.append(f'  rowK_eq {i} ({expr})')
    P = sum(rowval[rs:re_])
    out.append(f'\ntheorem seg_{k} : blkK {rs} = {lit(P)} + blkK {re_} := by')
    names = []
    for i in range(rs, re_):
        if sg[i] == 0:
            out.append(f'  have e{i} := blkK_step_zero {i} {i + 1} rfl (by norm_num) (by decide +kernel)')
        else:
            out.append(f'  have e{i} := blkK_step_row {i} {i + 1} rfl (by norm_num) (by decide +kernel) rk_{i}')
        names.append(f'e{i}')
    out.append('  linear_combination ' + ' + '.join(names))
    out.append('\nend Trace86.Cert\n')
    open(f'{H}/Trace86/EKR{k:03d}.lean', 'w').write('\n'.join(out))
    segs.append((k, rs, re_, P))
out = [f'import Trace86.EKR{k:03d}' for k, _, _, _ in segs] + ['import T86K.ELitsEq', '',
       f'/-! The energy check (K): `(iBlock 0 {NREC}).1` from the segment sums, the inequality decided by',
       '`T86N.energy_ok` in the N track, and `I ≥ iLoNum / 2^128`. Generated by tools/gen86_ekassembly.py. -/', '',
       'set_option maxHeartbeats 0', '',
       'namespace Trace86.Cert', '', 'open T86Core AuxCore AuxCommon', '',
       f'theorem blkK_zero : blkK 0 = {lit(TOTAL)} := by',
       '  linear_combination ' + ' + '.join(f'seg_{k}' for k, _, _, _ in segs) + ' + blkK_end', '',
       f'theorem iBlock_fst_eq_blkK : (iBlock 0 {NREC}).1 = blkK 0 := by',
       '  rw [iBlock_eq_aux, T86Core.T86K.tabI_eq, T86Core.T86K.l2I_eq, T86Core.T86K.recsI_eq]',
       '  unfold blkK lDecL',
       '  rw [Nat.sub_zero]', '',
       f'theorem energy_okK : (iLoNum : ℤ) * 12 * 10 ^ 48 * 2 ^ 300 ≤ (iBlock 0 {NREC}).1 * 2 ^ 128 := by',
       '  rw [iBlock_fst_eq_blkK, blkK_zero]',
       '  decide +kernel', '',
       'theorem IR_ge_K : (iLoNum : ℝ) / 2 ^ 128 ≤ IR := energy_sound energy_okK', '',
       'end Trace86.Cert', '']
open(f'{H}/Trace86/EnergyK.lean', 'w').write('\n'.join(out))
print(len(segs), 'EKR files; TOTAL matches')
