#!/usr/bin/env python3
"""Generate Trace86/LeavesN.lean: the full tiling check `leavesOKE (mkCtx iLoNum 128) X0 k0 leaves XT kT = true`
from the N shards T86N/ChunkNNN.lean (native_decide), composed by `chunk_stepE` from the last shard backwards.
Fork of the companion Mahler-measure formalization's leaves composition generator."""
import re, glob, os
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # the project root (parent of tools/)
rows = []
for f in sorted(glob.glob(f'{H}/T86N/Chunk*.lean'), key=lambda f: int(re.search(r'Chunk(\d+)\.lean$', f).group(1))):
    s = open(f).read()
    m = re.search(r'theorem (chunk_\d+) :\s*leavesOKE \(mkCtx iLoNum 128\) (\d+) (\d+) \(\(leaves\.drop (\d+)\)\.take (\d+)\) (\d+) (\d+) = true', s)
    name = m.group(1)
    rows.append((os.path.basename(f)[:-5], name) + tuple(int(x) for x in m.groups()[1:]))
for a, b in zip(rows, rows[1:]):
    assert a[6:8] == b[2:4] and a[4] + a[5] == b[4]
n = len(rows)
# number of positive-weight polynomials, from the data module
dl = next(l for l in open(f'{H}/T86Core/Data.lean') if l.startswith('def polys : List (List Int) := ['))
JJ = len(re.findall(r'\[-?\d+(?:, -?\d+)*\]', dl.split(':=', 1)[1]))
last = rows[-1]
total = last[4] + last[5]
out = []
out.append('\n'.join(f'import T86N.{r[0]}' for r in rows))
out.append('import Trace86.CheckSoundE5\n')
out.append('/-! The complete tiling check (N): the shards `T86N.chunk_NNN` composed. Generated by tools/gen86_leavesN.py. -/\n')
out.append('open Set\n\nnamespace Trace86.Cert\n\nopen T86Core AuxCore AuxCommon\n')
out.append(f'set_option maxRecDepth 200000 in\ntheorem leaves_length : leaves.length = {total} := by decide +kernel\n')
XT, kT = last[6], last[7]
out.append(f'theorem leavesOK_full_N : leavesOKE (mkCtx iLoNum 128) {rows[0][2]} {rows[0][3]} leaves {XT} {kT} = true := by')
out.append(f'  have s{n-1} : leavesOKE (mkCtx iLoNum 128) {last[2]} {last[3]} (leaves.drop {last[4]}) {XT} {kT} = true := by')
out.append(f'    have h := T86Core.T86N.{last[1]}')
out.append(f'    rwa [List.take_of_length_le (by rw [List.length_drop, leaves_length])] at h')
for i in range(n - 2, -1, -1):
    r = rows[i]
    out.append(f'  have s{i} : leavesOKE (mkCtx iLoNum 128) {r[2]} {r[3]} (leaves.drop {r[4]}) {XT} {kT} = true :=')
    out.append(f'    chunk_stepE (a := {r[4]}) (n := {r[5]}) T86Core.T86N.{r[1]} s{i+1}')
out.append('  simpa using s0\n')
out.append(f'''/-- `F > 0` on `[{rows[0][2]} / (10^12 2^{rows[0][3]}), {XT} / (10^12 2^{kT}))` off the roots (N). -/
theorem FR_pos_leaves_N (hI : (iLoNum : ℝ) / 2 ^ 128 ≤ IR) :
    ∀ x ∈ Ico (({rows[0][2]} : ℕ) / (DEC * 2 ^ {rows[0][3]} : ℕ) : ℝ) (({XT} : ℕ) / (DEC * 2 ^ {kT} : ℕ) : ℝ),
      (∀ j < {JJ}, (QR (polys.getD j [])).eval x ≠ 0) → 0 < FR x :=
  (leavesOKE_sound hI leaves _ _ _ _ leavesOK_full_N).2

end Trace86.Cert
''')
open(f'{H}/Trace86/LeavesN.lean', 'w').write('\n'.join(out))
print('wrote', n, 'shards, end', XT, kT)
