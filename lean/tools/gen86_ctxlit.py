#!/usr/bin/env python3
"""Write T86Core/Lits.lean from the output of the native helper `t86k ctx INUM 128` (the checker context as a Lean
literal; the kernel checks `mkCtx iLoNum 128 = ctxLit` in T86K/Lits.lean). Paths are relative to the project root.
usage: python3 -I gen86_ctxlit.py CTX_OUT"""
import os, sys
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
body = open(sys.argv[1]).read().strip()
assert body.startswith('def ctxLit : Ctx where')
open(f'{H}/T86Core/Lits.lean', 'w').write(f'''import T86Core.Check

/-! The checker context `mkCtx iLoNum 128` as a literal (printed by the native helper `t86k ctx`, Bench/T86K.lean).
The kernel checks `mkCtx iLoNum 128 = ctxLit` in `T86K.Lits`, so the literal is not trusted; it only spares the kernel
from recomputing the records in every shard. Generated by tools/gen86_ctxlit.py. -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace T86Core

{body}

end T86Core
''')
print('ok', len(body))
