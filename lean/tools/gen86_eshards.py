#!/usr/bin/env python3
"""Generate the K energy shards T86K/EblkNNNN.lean (`iBlock i0 cnt = (lo, hi)` by decide +kernel, core-only closure)
from scratch/eblock_vals.txt (output of the native `t86k eblks scratch/eblocks.txt`), and scratch/eblocks_lean.txt
(index i0 cnt lo hi) for the assembly generator. Fork of lean-aux's tools/gen_tp_eshards.py."""
import re, os
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # the project root (parent of tools/)
vals = {}
tot = None
for line in open(f'{H}/scratch/eblock_vals.txt'):
    m = re.match(r'block (\d+) (\d+): lo (-?\d+) hi (-?\d+)', line)
    if m:
        vals[(int(m.group(1)), int(m.group(2)))] = (int(m.group(3)), int(m.group(4)))
    m = re.match(r'sum: lo (-?\d+) hi (-?\d+)', line)
    if m:
        tot = (int(m.group(1)), int(m.group(2)))
blocks = [tuple(int(x) for x in l.split()) for l in open(f'{H}/scratch/eblocks.txt')]
assert blocks[0][0] == 0 and all(a[0] + a[1] == b[0] for a, b in zip(blocks, blocks[1:])) and sum(b[1] for b in blocks) == 1753
assert sum(vals[b][0] for b in blocks) == tot[0] and sum(vals[b][1] for b in blocks) == tot[1], 'blocks do not add up'
def lit(v):
    return f'({v})' if v < 0 else str(v)
with open(f'{H}/scratch/eblocks_lean.txt', 'w') as f:
    for idx, b in enumerate(blocks):
        lo, hi = vals[b]
        f.write(f'{idx} {b[0]} {b[1]} {lo} {hi}\n')
        open(f'{H}/T86K/Eblk{idx:04d}.lean', 'w').write(f'''import T86Core.Check

/-! Energy shard {idx} (K): rows {b[0]} .. {b[0] + b[1] - 1}. Generated by tools/gen86_eshards.py. -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace T86Core.T86K

theorem eblk_{idx:04d} : iBlock {b[0]} {b[1]} = ({lit(lo)}, {lit(hi)}) := by decide +kernel

end T86Core.T86K
''')
print(len(blocks), 'shards; sums match the total block')
