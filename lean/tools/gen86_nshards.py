"""Emit the N (native_decide) or K (decide +kernel) shard modules of the 86a lower bound: Globals (data, energy, tails;
in K mode without the energy, which has its own chunk files, tools/gen86_echunks.py) and, in N mode, Chunk modules
(contiguous blocks of leaves between literal end points, checked by `leavesOKE`; the K leaves are end-point shards,
tools/gen86_epshards.py). Adapted from the companion shard generator.
usage: python3 -I gen86_nshards.py leaves.json NCHUNK MODE(N|K) OUTDIR XLO XHI NREC"""
import json, sys
from fractions import Fraction as Fr
DEC = 10 ** 12
d = json.load(open(sys.argv[1])); n = int(sys.argv[2]); mode = sys.argv[3]; outdir = sys.argv[4]
XLO, XHI, NREC = int(sys.argv[5]), int(sys.argv[6]), int(sys.argv[7])
L = [(Fr(l['Xp'], DEC << l['k']), l['Xp'], l['k']) for l in d['chord']] + [(Fr(w['Xu'], DEC << w['k']), w['Xu'], w['k']) for w in d['windows']]
L.sort(key=lambda t: t[0])
N = len(L); per = -(-N // n)
pref = 'T86N' if mode == 'N' else 'T86K'
tac = 'native_decide' if mode == 'N' else 'decide +kernel'
ctx = '(mkCtx iLoNum 128)' if mode == 'N' else 'ctxLit'
imports = 'import T86Core.Leaves\nimport T86Core.CheckE' if mode == 'N' else 'import T86Core.Lits\nimport T86Core.Leaves'
names = []
for ci, a in enumerate(range(0, N, per) if mode == 'N' else []):
    b = min(a + per, N)
    X1, k1 = L[a][1], L[a][2]
    X2, k2 = (L[b][1], L[b][2]) if b < N else (XHI, 0)
    W = max(3 if N <= per * 1000 else 4, len(str(-(-N // per) - 1)))   # names of equal width (sort order = index order)
    name = f'Chunk{ci:0{W}d}'
    names.append((name, a, b - a, X1, k1, X2, k2))
    open(f'{outdir}/{name}.lean', 'w').write(f'''{imports}

/-! Shard {ci} of the 86a tiling ({mode}): leaves {a} .. {b - 1}. Generated by tools/gen86_nshards.py. -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace T86Core.{pref}

theorem chunk_{ci:0{W}d} :
    leavesOKE {ctx} {X1} {k1} ((leaves.drop {a}).take {b - a}) {X2} {k2} = true := by
  {tac}

end T86Core.{pref}
''')
energy = f'''/-- `I ≥ iLoNum / 2^128`: the energy blocks give `I ≥ iBlock.1 / (12 · 10^48 · 2^300)`. -/
theorem energy_ok : decide ((iLoNum : Int) * 12 * 10 ^ 48 * 2 ^ 300 ≤ (iBlock 0 {NREC}).1 * 2 ^ 128) = true := by
  {tac}
''' if mode == 'N' else ''
open(f'{outdir}/Globals.lean', 'w').write(f'''{imports}

/-! Global checks of the 86a lower-bound certificate ({mode}): data, energy, tails. Generated by tools/gen86_nshards.py. -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace T86Core.{pref}

theorem data_ok : dataOK = true := by {tac}

{energy}
theorem left_tail_ok : (leftTailPre {XLO} 0 && decide (0 < leftTailLB {ctx} {XLO} 0)) = true := by
  {tac}

theorem right_tail_ok : (rightTailPre {XHI} && decide (0 < rightTailLB {ctx} {XHI})) = true := by
  {tac}

end T86Core.{pref}
''')
print(len(names), 'chunks of', per)
json.dump(names, open(f'{outdir}/chunks.json', 'w'))
