#!/usr/bin/env python3
"""Generate Trace86U/LeavesN.lean: the full tiling check `leavesOK mkCtx X0 k0 leaves XT kT = true`
from the N shards T86N/ChunkNNN.lean (native_decide), composed by `chunk_step` from the last shard backwards.
Fork of tools/gen86_leavesN.py (upper)."""
import re, glob, os
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # the project root (parent of tools/)
rows = []
for f in sorted(glob.glob(f'{H}/T86UN/Chunk*.lean'), key=lambda f: int(re.search(r'Chunk(\d+)\.lean$', f).group(1))):
    s = open(f).read()
    m = re.search(r'theorem (chunk_\d+) :\s*leavesOK mkCtx (\d+) (\d+) \(\(leaves\.drop (\d+)\)\.take (\d+)\) (\d+) (\d+) = true', s)
    name = m.group(1)
    rows.append((os.path.basename(f)[:-5], name) + tuple(int(x) for x in m.groups()[1:]))
for a, b in zip(rows, rows[1:]):
    assert a[6:8] == b[2:4] and a[4] + a[5] == b[4]
n = len(rows)
last = rows[-1]
total = last[4] + last[5]
out = []
out.append('\n'.join(f'import T86UN.{r[0]}' for r in rows))
out.append('import Trace86U.CheckSound10\n')
out.append('/-! The complete upper tiling check (N): the shards `T86UN.chunk_NNN` composed. Generated by tools/gen86u_leavesN.py. -/\n')
out.append('open Set\n\nnamespace Trace86.UCert\n\nopen T86UCore AuxCore AuxCommon\n')
out.append(f'set_option maxRecDepth 200000 in\ntheorem leaves_length : leaves.length = {total} := by decide +kernel\n')
out.append('''theorem take_append_drop' (l : List Leaf) (a n : ℕ) : (l.drop a).take n ++ l.drop (a + n) = l.drop a := by
  have h := List.take_append_drop n (l.drop a)
  rwa [List.drop_drop] at h

theorem chunk_step {c : Ctx} {X kx Y ky XT kT a n : ℕ}
    (h1 : leavesOK c X kx ((leaves.drop a).take n) Y ky = true)
    (h2 : leavesOK c Y ky (leaves.drop (a + n)) XT kT = true) :
    leavesOK c X kx (leaves.drop a) XT kT = true := by
  have h := leavesOK_append c _ _ X kx Y ky XT kT h1 h2
  rwa [take_append_drop'] at h
''')
XT, kT = last[6], last[7]
out.append(f'theorem leavesOK_full_N : leavesOK mkCtx {rows[0][2]} {rows[0][3]} leaves {XT} {kT} = true := by')
out.append(f'  have s{n-1} : leavesOK mkCtx {last[2]} {last[3]} (leaves.drop {last[4]}) {XT} {kT} = true := by')
out.append(f'    have h := T86UCore.T86UN.{last[1]}')
out.append(f'    rwa [List.take_of_length_le (by rw [List.length_drop, leaves_length])] at h')
for i in range(n - 2, -1, -1):
    r = rows[i]
    out.append(f'  have s{i} : leavesOK mkCtx {r[2]} {r[3]} (leaves.drop {r[4]}) {XT} {kT} = true :=')
    out.append(f'    chunk_step (a := {r[4]}) (n := {r[5]}) T86UCore.T86UN.{r[1]} s{i+1}')
out.append('  simpa using s0\n')
out.append(f'''/-- `F > 0` on `[{rows[0][2]} / (10^12 2^{rows[0][3]}), {XT} / (10^12 2^{kT}))` off the roots (N). -/
theorem FR_pos_leaves_N :
    ∀ x ∈ Ico (({rows[0][2]} : ℕ) / (DEC * 2 ^ {rows[0][3]} : ℕ) : ℝ) (({XT} : ℕ) / (DEC * 2 ^ {kT} : ℕ) : ℝ),
      (∀ j < 21, (QR (polys.getD j [])).eval x ≠ 0) → 0 < FR x :=
  (leavesOK_sound leaves _ _ _ _ leavesOK_full_N).2

end Trace86.UCert
''')
open(f'{H}/Trace86U/LeavesN.lean', 'w').write('\n'.join(out))
print('wrote', n, 'shards, end', XT, kT)
