#!/usr/bin/env python3
"""Write T86K/ELits.lean (literal energy table and records, printed by the native `t86k elits`) and T86K/ELitsEq.lean
(the kernel checks that they equal TABI, L2I and recsI). Paths are relative to the project root (the parent of tools/).
Fork of the companion areal formalization's tools/gen_arl_elits.py.
usage: python3 -I gen86_elits.py ELITS_OUT"""
import os, sys
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
body = open(sys.argv[1]).read().strip()
os.makedirs(f'{H}/T86K', exist_ok=True)
assert body.startswith('def tabILit')
open(f'{H}/T86K/ELits.lean', 'w').write(f'''import T86Core.Check

/-! Literal copies of the energy data (K): the table `TABI`, `L2I`, `logI TABI L2I DEC 1` and the records `recsI`.
Printed by the native helper `t86k elits` (Bench/T86K.lean); `T86K.ELitsEq` checks them in the kernel.
Generated by tools/gen86_elits.py. -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace T86Core

{body}

def dfl : NRec := ⟨0, 0, 0, 0⟩

/-- `log 10^12` at scale `2^PI`, from the literal table. -/
def lDecL : Int × Int := logI tabILit l2ILit DEC 1

end T86Core
''')
open(f'{H}/T86K/ELitsEq.lean', 'w').write('''import T86K.ELits

/-! The literal energy data equal the computed ones (K). -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace T86Core.T86K

theorem tabI_eq : TABI = tabILit := by decide +kernel

theorem l2I_eq : L2I = l2ILit := by decide +kernel

theorem recsI_eq : recsI = recsILit := by decide +kernel

end T86Core.T86K
''')
print('ok', len(body))
