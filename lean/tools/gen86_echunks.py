#!/usr/bin/env python3
"""Generate the K energy chunk shards T86K/EchkNNNN.lean from scratch/echunk_vals.txt (lines `i a m lo`: native lower
ends of `iRow TABI L2I (logI TABI L2I DEC 1) (recsI.getD i _) ((recsI.drop a).take m)`, from `t86k irows`), and
scratch/echunk_map.txt (file index per chunk). Each theorem is kernel-checked over the literal inputs of T86K/ELits.lean
(`decide +kernel`, core-only closure); rows are cut into chunks of at most 200 columns, since the kernel's cost grows
faster than linearly. The chunk lows must add up to the native `(iBlock 0 NREC).1` in scratch/eblock_total.txt (output of
`t86k eblk 0 NREC`). Paths are relative to the project root. Fork of the companion areal formalization's
tools/gen_arl_echunks.py.
usage: python3 -I gen86_echunks.py"""
import os, re
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = [l.split() for l in open(f'{H}/scratch/echunk_vals.txt') if l.strip()]
os.makedirs(f'{H}/T86K', exist_ok=True)
PER = 30
TLO = int(re.search(r'lo (-?\d+)', open(f'{H}/scratch/eblock_total.txt').read()).group(1))
assert sum(int(r[3]) for r in rows) == TLO, 'chunk lows do not add up to the native (iBlock 0 NREC).1'
def lit(v): return f'({v})' if v < 0 else str(v)
nfiles = 0
with open(f'{H}/scratch/echunk_map.txt', 'w') as mp:
    for f0 in range(0, len(rows), PER):
        idx = f0 // PER
        body = []
        for r in rows[f0:f0 + PER]:
            i, a, m, lo = int(r[0]), int(r[1]), int(r[2]), int(r[3])
            body.append(f'theorem ec_{i}_{a} : (iRow tabILit l2ILit lDecL (recsILit.getD {i} dfl) ((recsILit.drop {a}).take {m})).1 =\n'
                        f'    {lit(lo)} := by decide +kernel\n')
            mp.write(f'{i} {a} {m} {idx}\n')
        open(f'{H}/T86K/Echk{idx:04d}.lean', 'w').write(
            'import T86K.ELits\n\n'
            f'/-! Energy chunks (K), file {idx}. Generated by tools/gen86_echunks.py. -/\n\n'
            'set_option maxRecDepth 200000\nset_option maxHeartbeats 0\n\nnamespace T86Core.T86K\n\n'
            + '\n'.join(body) + '\nend T86Core.T86K\n')
        nfiles += 1
print(nfiles, 'files;', len(rows), 'chunks; sum matches the native total')
