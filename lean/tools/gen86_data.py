#!/usr/bin/env python3
"""Generate T86Core/Data.lean from the 86a lower-bound certificate (JSON: A, lamQ, nodes, rho, lambda, x_lo, x_hi).
Zero-weight polynomials are dropped (they do not occur in F). usage: python3 -I gen86_data.py CERT.json OUT.lean"""
import json, sys, hashlib
from fractions import Fraction as Fr
DEC = 10 ** 12
raw = open(sys.argv[1], 'rb').read(); c = json.loads(raw)
lam = [Fr(x) for x in c['lamQ']]
polys = [q for q, l in zip(c['A'], lam) if l != 0]
cw = [l for l in lam if l != 0]
assert all(x > 0 and x.denominator & (x.denominator - 1) == 0 for x in cw)
assert polys[0] == [1, 0]
nodes = [Fr(x) for x in c['nodes']]
assert all((x * DEC).denominator == 1 for x in nodes) and all(a < b for a, b in zip(nodes, nodes[1:]))
rho = [Fr(x) for x in c['rho']]
RS = max(x.denominator for x in rho).bit_length() - 1
assert all(x >= 0 and (x * 2 ** RS).denominator == 1 for x in rho) and len(rho) == len(nodes) - 2
L = Fr(c['lambda']); xlo = Fr(c['x_lo']); xhi = Fr(c['x_hi'])
assert (xlo * DEC).denominator == 1 and (xhi * DEC).denominator == 1
def ilist(v): return "[" + ", ".join(str(x) for x in v) + "]"
out = [f"/-! Data of the 86a lower-bound certificate `{sys.argv[1].split('/')[-1]}`, generated by tools/gen86_data.py.",
       f"Input SHA-256: {hashlib.sha256(raw).hexdigest()}. Zero-weight polynomials dropped. Core Lean only. -/", "",
       "set_option maxRecDepth 200000", "", "namespace T86Core", "",
       "/-- The polynomials `Q_j` with positive weight, coefficients from the leading one down to the constant term.",
       "`Q_0 = x`. -/",
       "def polys : List (List Int) := [" + ", ".join(ilist(q) for q in polys) + "]",
       "/-- The weights `c_j = cwNum_j / 2^cwSh_j`. -/",
       "def cwNum : List Nat := " + ilist([x.numerator for x in cw]),
       "def cwSh : List Nat := " + ilist([x.denominator.bit_length() - 1 for x in cw]),
       "/-- The nodes `e_i = nodes_i / 10^12`. -/",
       "def nodes : List Nat := " + ilist([int(x * DEC) for x in nodes]),
       "/-- The hat weights `ρ_k = rho_k / 2^RS` (`k = 1 … N-1`; the hat on `[e_{k-1}, e_{k+1}]` has mass `1`). -/",
       f"def RS : Nat := {RS}",
       "def rho : List Nat := " + ilist([int(x * 2 ** RS) for x in rho]),
       "/-- `λ = lamNum / lamDen`. -/",
       f"def lamNum : Nat := {L.numerator}", f"def lamDen : Nat := {L.denominator}",
       "/-- `x_lo = XLO / 10^12`, `x_hi = XHI / 10^12`. -/",
       f"def XLO : Nat := {int(xlo * DEC)}", f"def XHI : Nat := {int(xhi * DEC)}", "",
       "end T86Core", ""]
open(sys.argv[2], 'w').write("\n".join(out))
print(len(polys), 'polys', len(nodes), 'nodes', len(rho), 'hats, RS', RS)
