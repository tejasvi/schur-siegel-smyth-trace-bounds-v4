"""Emit T86UCore/Leaves.lean (core Lean: the leaves of the [x0, 6] tiling and the root brackets of condition (M)) and a
text list of the leaves, from the output of t86u_check_ref.py. Untrusted hints: the checker verifies everything.
Fork of tools/gen86_leaves.py.
usage: python3 -I gen86u_leaves.py leaves_ub.json OUT.lean OUT.txt XLO_NUM XHI_NUM [moments.json]"""
import json, sys, hashlib
from fractions import Fraction as Fr
DEC = 10 ** 12
raw = open(sys.argv[1], 'rb').read(); sha = hashlib.sha256(raw).hexdigest()
d = json.loads(raw)
XLO, XHI = int(sys.argv[4]), int(sys.argv[5])
L = [(Fr(l['Xp'], DEC << l['k']), 0, l['Xp'], l['Xq'], l['k'], bool(l['x0q']), l['mask']) for l in d['chord']]
L += [(Fr(w['Xu'], DEC << w['k']), 1, w['Xu'], w['Xv'], w['k'], False, 0) for w in d['windows']]
L.sort(key=lambda t: t[0])
for a, b in zip(L, L[1:]):
    assert Fr(a[3], DEC << a[4]) == Fr(b[2], DEC << b[4]), (a, b)
assert L[0][0] == Fr(XLO, DEC), L[0]
assert Fr(L[-1][3], DEC << L[-1][4]) == Fr(XHI, DEC), L[-1]
moms = d['moments'] if d.get('moments') else json.load(open(sys.argv[6]))   # optional 6th argument: moments json
moms = sorted(moms, key=lambda m: m['j'])
assert [m['j'] for m in moms] == list(range(len(moms)))
out = ['import T86UCore.Check', '',
       f'/-! Leaves of the 86a upper tiling and root brackets, generated by tools/gen86u_leaves.py from',
       f'{sys.argv[1].split("/")[-1]} (sha256 {sha}). -/',
       '', 'set_option maxRecDepth 200000', 'set_option maxHeartbeats 0', '', 'namespace T86UCore', '',
       'def leaves : List Leaf := [']
out.append(',\n'.join(f'  ⟨{t[1]}, {t[2]}, {t[3]}, {t[4]}, {"true" if t[5] else "false"}, {t[6]}⟩' for t in L))
out += [']', '', '/-- Root brackets of condition (M): `(k_j, [(l, u), …])` for each `Q_j`, points `X / (10^12 2^k_j)`. -/',
        'def mom : List (Nat × List (Nat × Nat)) := [']
out.append(',\n'.join('  (' + str(m['k']) + ', [' + ', '.join(f'({a}, {b})' for a, b in m['bs']) + '])' for m in moms))
out += [']', '', 'end T86UCore', '']
open(sys.argv[2], 'w').write('\n'.join(out))
with open(sys.argv[3], 'w') as f:
    for t in L:
        f.write(f'C {t[2]} {t[3]} {t[4]} {1 if t[5] else 0} {t[6]}\n' if t[1] == 0 else f'W {t[2]} {t[3]} {t[4]}\n')
print('leaves', len(L), 'moment polys', len(moms), 'sha', sha)
