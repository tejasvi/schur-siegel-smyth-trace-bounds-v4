#!/usr/bin/env python3
"""Generate the leaves part of the K assembly of the 86a lower bound from the K shards (the energy part is
tools/gen86_ekassembly.py):
* Trace86/LeavesKG/GNN.lean: groups of chunk shards T86KL/ChunkNNNN (end-point form, tools/gen86_epshards.py) composed
  (`take_stepE`);
* Trace86/LeavesK.lean: the groups composed (`chunk_stepE`), `leavesOK_full_K`, `FR_pos_leaves_K`.
Paths are relative to the project root (the parent of tools/).
usage: python3 -I gen86_kassembly.py"""
import re, glob, os, json
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def lit(v):
    return f'({v})' if v < 0 else str(v)
# number of positive-weight polynomials, from the data module
dl = next(l for l in open(f'{H}/T86Core/Data.lean') if l.startswith('def polys : List (List Int) := ['))
JJ = len(re.findall(r'\[-?\d+(?:, -?\d+)*\]', dl.split(':=', 1)[1]))
# ---- leaves
rows = []
for f in sorted(glob.glob(f'{H}/T86KL/Chunk*.lean'), key=lambda f: int(re.search(r'Chunk(\d+)\.lean$', f).group(1))):
    s = open(f).read()
    m = re.search(r'theorem (chunk_\d+) :\s*leavesOKE ctxLit (\d+) (\d+) \(\(leaves\.drop (\d+)\)\.take (\d+)\) (\d+) (\d+) = true', s)
    rows.append((os.path.basename(f)[:-5], m.group(1)) + tuple(int(x) for x in m.groups()[1:]))
for a, b in zip(rows, rows[1:]):
    assert a[6:8] == b[2:4] and a[4] + a[5] == b[4]
G = 100
groups = [rows[i:i + G] for i in range(0, len(rows), G)]
os.makedirs(f'{H}/Trace86/LeavesKG', exist_ok=True)
for gi, g in enumerate(groups):
    o = [f'import T86KL.{r[0]}' for r in g]
    o += ['import Trace86.LeavesKGen', '',
          f'/-! Group {gi} of the K tiling shards. Generated by tools/gen86_kassembly.py. -/', '',
          'namespace Trace86.Cert', '', 'open T86Core', '']
    first, last = g[0], g[-1]
    tot = last[4] + last[5] - first[4]
    o.append(f'theorem group_{gi:02d} : leavesOKE ctxLit {first[2]} {first[3]} ((leaves.drop {first[4]}).take {tot}) {last[6]} {last[7]} = true := by')
    j = len(g) - 1
    o.append(f'  have s{j} := T86Core.T86KL.{g[j][1]}')
    for j in range(len(g) - 2, -1, -1):
        r = g[j]
        t = last[4] + last[5] - r[4]
        o.append(f'  have s{j} : leavesOKE ctxLit {r[2]} {r[3]} ((leaves.drop {r[4]}).take {t}) {last[6]} {last[7]} = true :=')
        o.append(f'    take_stepE (n := {r[5]}) (t := {t}) (b := {r[4] + r[5]}) rfl rfl T86Core.T86KL.{r[1]} s{j + 1}')
    o.append('  exact s0')
    o.append('\nend Trace86.Cert\n')
    open(f'{H}/Trace86/LeavesKG/G{gi:02d}.lean', 'w').write('\n'.join(o))
# top
ng = len(groups)
gr = []
for gi, g in enumerate(groups):
    first, last = g[0], g[-1]
    gr.append((gi, first[2], first[3], first[4], last[4] + last[5] - first[4], last[6], last[7]))
total = gr[-1][3] + gr[-1][4]
XT, kT = gr[-1][5], gr[-1][6]
o = [f'import Trace86.LeavesKG.G{gi:02d}' for gi in range(ng)]
o += ['import T86K.Lits', 'import Trace86.LeavesKGen', '',
      '/-! The complete tiling check (K): the groups of K shards composed. Generated by tools/gen86_kassembly.py. -/', '',
      'open Set', '', 'namespace Trace86.Cert', '', 'open T86Core AuxCore AuxCommon', '']
o.append(f'theorem leavesOK_full_ctxLit : leavesOKE ctxLit {gr[0][1]} {gr[0][2]} leaves {XT} {kT} = true := by')
g = gr[-1]
o.append(f'  have s{ng - 1} : leavesOKE ctxLit {g[1]} {g[2]} (leaves.drop {g[3]}) {XT} {kT} = true := by')
o.append(f'    have h := group_{ng - 1:02d}')
o.append(f'    rwa [List.take_of_length_le (by rw [List.length_drop, leaves_length_K])] at h')
for gi in range(ng - 2, -1, -1):
    g = gr[gi]
    o.append(f'  have s{gi} : leavesOKE ctxLit {g[1]} {g[2]} (leaves.drop {g[3]}) {XT} {kT} = true :=')
    o.append(f'    chunk_stepE (a := {g[3]}) (n := {g[4]}) group_{gi:02d} s{gi + 1}')
o.append('  simpa using s0\n')
o.append(f'''theorem leavesOK_full_K : leavesOKE (mkCtx iLoNum 128) {gr[0][1]} {gr[0][2]} leaves {XT} {kT} = true := by
  rw [T86Core.T86K.ctx_eq]
  exact leavesOK_full_ctxLit

/-- `F > 0` on `[{gr[0][1]} / (10^12 2^{gr[0][2]}), {XT} / (10^12 2^{kT}))` off the roots (K). -/
theorem FR_pos_leaves_K (hI : (iLoNum : ℝ) / 2 ^ 128 ≤ IR) :
    ∀ x ∈ Ico (({gr[0][1]} : ℕ) / (DEC * 2 ^ {gr[0][2]} : ℕ) : ℝ) (({XT} : ℕ) / (DEC * 2 ^ {kT} : ℕ) : ℝ),
      (∀ j < {JJ}, (QR (polys.getD j [])).eval x ≠ 0) → 0 < FR x :=
  (leavesOKE_sound hI leaves _ _ _ _ leavesOK_full_K).2

end Trace86.Cert
''')
open(f'{H}/Trace86/LeavesK.lean', 'w').write('\n'.join(o))
print('leaf chunks', len(rows), 'groups', ng)
