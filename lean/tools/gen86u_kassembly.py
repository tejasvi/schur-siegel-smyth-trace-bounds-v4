#!/usr/bin/env python3
"""Generate the K assembly of the 86a upper tiling from the K shards T86UK/ChunkNNNN: Trace86U/LeavesKG/GNN.lean (groups
of chunks, `take_step`) and Trace86U/LeavesK.lean (`leavesOK_full_K`). Fork of tools/gen86_kassembly.py (leaves part)."""
import re, glob, os, json
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # the project root (parent of tools/)
# ---- leaves
rows = []
for f in sorted(glob.glob(f'{H}/T86UK/Chunk*.lean'), key=lambda f: int(re.search(r'Chunk(\d+)\.lean$', f).group(1))):
    s = open(f).read()
    m = re.search(r'theorem (chunk_\d+) :\s*leavesOK ctxULit (\d+) (\d+) \(\(leaves\.drop (\d+)\)\.take (\d+)\) (\d+) (\d+) = true', s)
    rows.append((os.path.basename(f)[:-5], m.group(1)) + tuple(int(x) for x in m.groups()[1:]))
for a, b in zip(rows, rows[1:]):
    assert a[6:8] == b[2:4] and a[4] + a[5] == b[4]
G = 100
groups = [rows[i:i + G] for i in range(0, len(rows), G)]
os.makedirs(f'{H}/Trace86U/LeavesKG', exist_ok=True)
for gi, g in enumerate(groups):
    o = [f'import T86UK.{r[0]}' for r in g]
    o += ['import Trace86U.LeavesKGen', '',
          f'/-! Group {gi} of the K tiling shards. Generated by tools/gen86_kassembly.py. -/', '',
          'namespace Trace86.UCert', '', 'open T86UCore', '']
    first, last = g[0], g[-1]
    tot = last[4] + last[5] - first[4]
    o.append(f'theorem group_{gi:02d} : leavesOK ctxULit {first[2]} {first[3]} ((leaves.drop {first[4]}).take {tot}) {last[6]} {last[7]} = true := by')
    j = len(g) - 1
    o.append(f'  have s{j} := T86UCore.T86UK.{g[j][1]}')
    for j in range(len(g) - 2, -1, -1):
        r = g[j]
        t = last[4] + last[5] - r[4]
        o.append(f'  have s{j} : leavesOK ctxULit {r[2]} {r[3]} ((leaves.drop {r[4]}).take {t}) {last[6]} {last[7]} = true :=')
        o.append(f'    take_step (n := {r[5]}) (t := {t}) (b := {r[4] + r[5]}) rfl rfl T86UCore.T86UK.{r[1]} s{j + 1}')
    o.append('  exact s0')
    o.append('\nend Trace86.UCert\n')
    open(f'{H}/Trace86U/LeavesKG/G{gi:02d}.lean', 'w').write('\n'.join(o))
# top
ng = len(groups)
gr = []
for gi, g in enumerate(groups):
    first, last = g[0], g[-1]
    gr.append((gi, first[2], first[3], first[4], last[4] + last[5] - first[4], last[6], last[7]))
total = gr[-1][3] + gr[-1][4]
XT, kT = gr[-1][5], gr[-1][6]
o = [f'import Trace86U.LeavesKG.G{gi:02d}' for gi in range(ng)]
o += ['import T86UK.Lits', 'import Trace86U.LeavesKGen', '',
      '/-! The complete tiling check (K): the groups of K shards composed. Generated by tools/gen86_kassembly.py. -/', '',
      'open Set', '', 'namespace Trace86.UCert', '', 'open T86UCore AuxCore AuxCommon', '']
o.append(f'theorem leavesOK_full_ctxULit : leavesOK ctxULit {gr[0][1]} {gr[0][2]} leaves {XT} {kT} = true := by')
g = gr[-1]
o.append(f'  have s{ng - 1} : leavesOK ctxULit {g[1]} {g[2]} (leaves.drop {g[3]}) {XT} {kT} = true := by')
o.append(f'    have h := group_{ng - 1:02d}')
o.append(f'    rwa [List.take_of_length_le (by rw [List.length_drop, leaves_length_K])] at h')
for gi in range(ng - 2, -1, -1):
    g = gr[gi]
    o.append(f'  have s{gi} : leavesOK ctxULit {g[1]} {g[2]} (leaves.drop {g[3]}) {XT} {kT} = true :=')
    o.append(f'    chunk_step_K (a := {g[3]}) (n := {g[4]}) group_{gi:02d} s{gi + 1}')
o.append('  simpa using s0\n')
o.append(f'''theorem leavesOK_full_K : leavesOK mkCtx {gr[0][1]} {gr[0][2]} leaves {XT} {kT} = true := by
  rw [T86UCore.T86UK.ctx_eq]
  exact leavesOK_full_ctxULit

end Trace86.UCert
''')
open(f'{H}/Trace86U/LeavesK.lean', 'w').write('\n'.join(o))
print('upper leaf chunks', len(rows), 'groups', ng)
