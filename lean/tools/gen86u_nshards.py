"""Emit the N (native_decide) or K (decide +kernel) shard modules of the 86a upper bound: Globals (data, budget, trace,
moments, left tail) and Chunk modules (contiguous blocks of leaves between literal end points). Fork of
tools/gen86_nshards.py.
usage: python3 -I gen86u_nshards.py leaves_ub.json NCHUNK MODE(N|K) OUTDIR XLO XHI"""
import json, sys
from fractions import Fraction as Fr
DEC = 10 ** 12
d = json.load(open(sys.argv[1])); n = int(sys.argv[2]); mode = sys.argv[3]; outdir = sys.argv[4]
XLO, XHI = int(sys.argv[5]), int(sys.argv[6])
L = [(Fr(l['Xp'], DEC << l['k']), l['Xp'], l['k']) for l in d['chord']] + [(Fr(w['Xu'], DEC << w['k']), w['Xu'], w['k']) for w in d['windows']]
L.sort(key=lambda t: t[0])
N = len(L); per = -(-N // n)
pref = 'T86UN' if mode == 'N' else 'T86UK'
tac = 'native_decide' if mode == 'N' else 'decide +kernel'
ctx = 'mkCtx' if mode == 'N' else 'ctxULit'
imports = 'import T86UCore.Leaves' if mode == 'N' else 'import T86UCore.Lits\nimport T86UCore.Leaves'
names = []
W = 3 if N <= per * 1000 else 4
for ci, a in enumerate(range(0, N, per)):
    b = min(a + per, N)
    X1, k1 = L[a][1], L[a][2]
    X2, k2 = (L[b][1], L[b][2]) if b < N else (XHI, 0)
    name = f'Chunk{ci:0{W}d}'
    names.append((name, a, b - a, X1, k1, X2, k2))
    open(f'{outdir}/{name}.lean', 'w').write(f'''{imports}

/-! Shard {ci} of the 86a upper tiling ({mode}): leaves {a} .. {b - 1}. Generated by tools/gen86u_nshards.py. -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace T86UCore.{pref}

theorem chunk_{ci:0{W}d} :
    leavesOK {ctx} {X1} {k1} ((leaves.drop {a}).take {b - a}) {X2} {k2} = true := by
  {tac}

end T86UCore.{pref}
''')
moments = f'''theorem moments_ok : momentsOK {ctx} mom = true := by
  {tac}
''' if mode == 'N' else ''
if mode == 'K':
    for j in range(21):
        open(f'{outdir}/Mom{j:02d}.lean', 'w').write(f'''{imports}

/-! Moment shard {j} of the 86a upper certificate (K): condition (M) for `Q_{j}`. Generated by tools/gen86u_nshards.py. -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace T86UCore.{pref}

theorem mom_{j:02d} : momentOK ctxULit (polys.getD {j} []) (mom.getD {j} (0, [])).1 (mom.getD {j} (0, [])).2 = true := by
  decide +kernel

end T86UCore.{pref}
''')
open(f'{outdir}/Globals.lean', 'w').write(f'''{imports}

/-! Global checks of the 86a upper-bound certificate ({mode}): data, (S), (T), (M), left tail. Generated by
tools/gen86u_nshards.py. -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace T86UCore.{pref}

theorem data_ok : dataOK = true := by {tac}

theorem budget_ok : budgetOK = true := by {tac}

theorem trace_ok : traceOK = true := by {tac}

{moments}
theorem irred_ok : irredsOK mom = true := by {tac}

theorem left_tail_ok : (leftTailPre {XLO} 0 && decide (0 < leftTailLB {ctx} {XLO} 0)) = true := by
  {tac}

end T86UCore.{pref}
''')
print(len(names), 'chunks of', per)
json.dump(names, open(f'{outdir}/chunks.json', 'w'))
