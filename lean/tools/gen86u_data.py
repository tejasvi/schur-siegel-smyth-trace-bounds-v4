#!/usr/bin/env python3
"""Generate T86UCore/Data.lean from the 86a upper-bound certificate (JSON: A, b, nodes, w, eps).
usage: python3 -I gen86u_data.py CERT.json OUT.lean XLO"""
import json, sys, hashlib, math
from fractions import Fraction as Fr
DEC = 10 ** 12
raw = open(sys.argv[1], 'rb').read(); c = json.loads(raw)
XLO = int(sys.argv[3])
polys = c['A']
b = [Fr(x) for x in c['b']]
assert all(x > 0 and x.denominator & (x.denominator - 1) == 0 for x in b)
assert polys[0] == [1, 0] and all(q[0] == 1 for q in polys)
nodes = [Fr(x) for x in c['nodes']]
assert all((x * DEC).denominator == 1 for x in nodes) and all(p < q for p, q in zip(nodes, nodes[1:]))
assert nodes[0] == 0 and nodes[-1] == 6
w = [Fr(x) for x in c['w']]
assert all(x >= 0 for x in w) and sum(w) == 1 and len(w) == len(nodes) - 2
WD = 1
for x in w: WD = WD * x.denominator // math.gcd(WD, x.denominator)
eps = Fr(c['eps'])
LAMU = Fr(81383685642728309283453, 45035996273705240000000)   # λ_U of Trace86.Statement (lamU)
tr = (1 - eps) * sum(wk * (nodes[k] + nodes[k + 1] + nodes[k + 2]) / 3 for k, wk in enumerate(w)) + 3 * eps
assert tr == LAMU, tr
def ilist(v): return "[" + ", ".join(str(x) for x in v) + "]"
out = [f"/-! Data of the 86a upper-bound certificate `{sys.argv[1].split('/')[-1]}`, generated by tools/gen86u_data.py.",
       f"Input SHA-256: {hashlib.sha256(raw).hexdigest()}. Core Lean only. -/", "",
       "set_option maxRecDepth 200000", "", "namespace T86UCore", "",
       "/-- The polynomials `Q_j` (monic), coefficients from the leading one down to the constant term. `Q_0 = x`. -/",
       "def polys : List (List Int) := [" + ", ".join(ilist(q) for q in polys) + "]",
       "/-- The weights `b_j = cwNum_j / 2^cwSh_j`. -/",
       "def cwNum : List Nat := " + ilist([x.numerator for x in b]),
       "def cwSh : List Nat := " + ilist([x.denominator.bit_length() - 1 for x in b]),
       "/-- The nodes `e_i = nodes_i / 10^12` (`e_0 = 0`, `e_N = 6`). -/",
       "def nodes : List Nat := " + ilist([int(x * DEC) for x in nodes]),
       "/-- The hat weights `w_k = rho_k / WD` (`k = 1 … N-1`; the hat on `[e_{k-1}, e_{k+1}]` has mass `1`; `∑ w_k = 1`). -/",
       f"def WD : Nat := {WD}",
       "def rho : List Nat := " + ilist([int(x * WD) for x in w]),
       "/-- `ε = EPSN / EPSD`. -/",
       f"def EPSN : Nat := {eps.numerator}", f"def EPSD : Nat := {eps.denominator}",
       "/-- The claimed bound `λ_U = lamUNum / lamUDen` (the trace of `μ`; checked by `traceOK`). -/",
       f"def lamUNum : Nat := {LAMU.numerator}", f"def lamUDen : Nat := {LAMU.denominator}",
       "/-- The left tail `(0, XLO / 10^12]`; the tiling covers `[XLO, XHI] / 10^12`, `XHI / 10^12 = 6`. -/",
       f"def XLO : Nat := {XLO}", f"def XHI : Nat := {6 * DEC}", "",
       "end T86UCore", ""]
open(sys.argv[2], 'w').write("\n".join(out))
print(len(polys), 'polys', len(nodes), 'nodes', len(w), 'hats, WD', WD, 'eps', eps)
