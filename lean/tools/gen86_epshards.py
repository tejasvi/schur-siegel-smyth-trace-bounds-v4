#!/usr/bin/env python3
"""Kernel-track (K) shards of the 86a tiling in the end-point form (T86Core.CheckE). Paths are relative to the project
root (the parent of tools/).
* `list LEAVES.json`: the reduced end points of the chord leaves (`canon`), one `X k` per line, to scratch/eps.txt
  (input of the native helper `t86k eps`, whose output scratch/eplits.txt is untrusted: the kernel checks every value);
* `emit LEAVES.json`: T86KE/EpNNNNN.lean, one end-point theorem `epDataKA ctxLit k X = ⟨...⟩` each, and
  T86KL/ChunkNNNN.lean, blocks of B consecutive leaves (chords and windows, in tiling order), each proving
  `leavesOKE ctxLit X k ((leaves.drop a).take n) X' k' = true` from its end-point theorems (`leafOKE_of_parts`) and one
  `chordOKC` (or `windowOK`) check per leaf.
usage: python3 -I gen86_epshards.py list LEAVES.json | python3 -I gen86_epshards.py emit LEAVES.json XHI [B]"""
import json, sys, os
from fractions import Fraction as Fr
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEC = 10 ** 12

def canon(X, k):
    while k > 0 and X % 2 == 0:
        X >>= 1; k -= 1
    return X, k

mode, path = sys.argv[1], sys.argv[2]
d = json.load(open(path))
# the leaves in tiling order, as in tools/gen86_leaves.py: (kind, X1, X2, k, x0q, mask)
L = [(Fr(l['Xp'], DEC << l['k']), 0, l['Xp'], l['Xq'], l['k'], bool(l['x0q']), l['mask']) for l in d['chord']]
L += [(Fr(w['Xu'], DEC << w['k']), 1, w['Xu'], w['Xv'], w['k'], False, 0) for w in d['windows']]
L.sort(key=lambda t: t[0])
L = [t[1:] for t in L]
eps = []; idx = {}
for t in L:
    if t[0] != 0: continue
    for X in (t[1], t[2]):
        c = canon(X, t[3])
        if c not in idx:
            idx[c] = len(eps); eps.append(c)
if mode == 'list':
    os.makedirs(f'{H}/scratch', exist_ok=True)
    with open(f'{H}/scratch/eps.txt', 'w') as f:
        for X, k in eps: f.write(f'{X} {k}\n')
    print('leaves', len(L), 'chord', sum(1 for t in L if t[0] == 0), 'end points', len(eps))
    sys.exit(0)
XHI = int(sys.argv[3]); B = int(sys.argv[4]) if len(sys.argv) > 4 else 25
lits = {}
for ln in open(f'{H}/scratch/eplits.txt'):
    x, k, rest = ln.split(' ', 2)
    lits[(int(x), int(k))] = rest.strip()
assert all(e in lits for e in eps), 'missing end-point literals'
W = max(5, len(str(len(eps) - 1)))
os.makedirs(f'{H}/T86KE', exist_ok=True); os.makedirs(f'{H}/T86KL', exist_ok=True)
head = '''set_option maxRecDepth 200000
set_option maxHeartbeats 0
'''
for i, (X, k) in enumerate(eps):
    open(f'{H}/T86KE/Ep{i:0{W}d}.lean', 'w').write(f'''import T86Core.Lits
import T86Core.CheckE

/-! End point {i} of the 86a tiling (K): `{X} / (10^12 2^{k})`. Generated by tools/gen86_epshards.py. -/

{head}
namespace T86Core.T86KE

theorem ep_{i:0{W}d} : epDataKA ctxLit {k} {X} =
    {lits[(X, k)]} := by
  decide +kernel

end T86Core.T86KE
''')
def lf(t):
    return f'⟨{t[0]}, {t[1]}, {t[2]}, {t[3]}, {"true" if t[4] else "false"}, {t[5]}⟩'
blocks = [(a, min(a + B, len(L))) for a in range(0, len(L), B)]
WC = max(4, len(str(len(blocks) - 1)))
for ci, (a, b) in enumerate(blocks):
    part = L[a:b]
    X1, k1 = part[0][1], part[0][3]
    X2, k2 = (L[b][1], L[b][3]) if b < len(L) else (XHI, 0)
    need = sorted({idx[canon(X, t[3])] for t in part if t[0] == 0 for X in (t[1], t[2])})
    imps = '\n'.join(f'import T86KE.Ep{i:0{W}d}' for i in need)
    steps = []
    for t in part:
        if t[0] == 0:
            ia = idx[canon(t[1], t[3])]; ib = idx[canon(t[2], t[3])]
            steps.append(f'leavesOKE_cons rfl (leafOKE_of_parts (by decide) T86Core.T86KE.ep_{ia:0{W}d} (by decide) '
                         f'T86Core.T86KE.ep_{ib:0{W}d} (by decide +kernel)) <|')
        else:
            steps.append(f'leavesOKE_cons rfl (by decide +kernel : leafOKE ctxLit {lf(t)} = true) <|')
    body = '\n    '.join(steps)
    lst = ',\n      '.join(lf(t) for t in part)
    open(f'{H}/T86KL/Chunk{ci:0{WC}d}.lean', 'w').write(f'''import T86Core.Lits
import T86Core.Leaves
{imps}

/-! Shard {ci} of the 86a tiling (K, end-point form): leaves {a} .. {b - 1}. Generated by tools/gen86_epshards.py. -/

{head}
namespace T86Core.T86KL

theorem chunk_{ci:0{WC}d} :
    leavesOKE ctxLit {X1} {k1} ((leaves.drop {a}).take {b - a}) {X2} {k2} = true := by
  have e : (leaves.drop {a}).take {b - a} = [
      {lst}] := by decide +kernel
  rw [e]
  exact
    {body}
    leavesOKE_nil rfl

end T86Core.T86KL
''')
with open(f'{H}/scratch/eplist_ep.txt', 'w') as f:
    for i in range(len(eps)): f.write(f'T86KE/Ep{i:0{W}d}.lean\n')
with open(f'{H}/scratch/eplist_chunks.txt', 'w') as f:
    for ci in range(len(blocks)): f.write(f'T86KL/Chunk{ci:0{WC}d}.lean\n')
print('end points', len(eps), 'chunks', len(blocks))
